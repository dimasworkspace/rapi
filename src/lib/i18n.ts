const dictionaries = { id, en }
export type Dict = typeof id

/** Hook utama i18n — kembalikan kamus sesuai bahasa aktif. */
export function useT(): Dict {
  const lang = useSettingsStore((s) => s.lang)
  return dictionaries[lang]
}

/** Akses non-reaktif (di luar React, mis. formatter). */
export const getDict = (): Dict => dictionaries[useSettingsStore.getState().lang]
